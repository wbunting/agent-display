"""Regenerate src/cli_text.rs from the Python reference's argparse parser.

usage: COLUMNS=80 python3 -I tools/gen_cli_text.py PATH/TO/agent-display > src/cli_text.rs

Usage and help texts are argparse's own output (80 columns, as when stdout
is not a terminal), so `-h` and usage errors match the Python tool.
"""
import argparse, importlib.machinery, importlib.util, json, os, sys

os.environ['COLUMNS'] = '80'
os.environ['NO_COLOR'] = '1'
loader = importlib.machinery.SourceFileLoader('ad', sys.argv[1])
spec = importlib.util.spec_from_loader('ad', loader)
ad = importlib.util.module_from_spec(spec)
loader.exec_module(ad)

texts = []


def walk(p):
    texts.append((p.prog, p.format_usage(), p.format_help()))
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            for sub in a.choices.values():
                walk(sub)


walk(ad.parser())
print('// Generated by tools/gen_cli_text.py from the Python agent-display. Do not edit.')
print('// (prog, usage, help) as argparse prints them at 80 columns.')
print('pub const TEXTS: &[(&str, &str, &str)] = &[')
for prog, usage, help_ in texts:
    print(f'    ({json.dumps(prog)}, {json.dumps(usage)}, {json.dumps(help_)}),')
print('];')
