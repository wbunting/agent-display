pub fn button(name: &str) -> &'static str {
    match name {
        "middle" => "button2",
        "right" => "button3",
        _ => "button1",
    }
}

pub fn scroll_button(dir: &str) -> &'static str {
    match dir {
        "up" => "button4",
        "down" => "button5",
        "left" => "button6",
        _ => "button7",
    }
}

pub fn check_point(ctx: &Ctx, disp: &Disp, x: i64, y: i64) -> Result<()> {
    let outs = sway_json(ctx, disp, "get_outputs")?;
    for o in outs.as_array().into_iter().flatten() {
        let r = &o["rect"];
        let (rx, ry, rw, rh) = (num(&r["x"]), num(&r["y"]), num(&r["width"]), num(&r["height"]));
        if rx <= x && x < rx + rw && ry <= y && y < ry + rh {
            return Ok(());
        }
    }
    bail!("({x},{y}) is outside the agent output");
}

pub fn cmd_move(ctx: &Ctx, x: i64, y: i64) -> Result<i32> {
    let disp = display(ctx)?;
    check_point(ctx, &disp, x, y)?;
    sway_cmd(ctx, &disp, &format!("seat seat0 cursor set {x} {y}"))?;
    Ok(0)
}

fn press(ctx: &Ctx, disp: &Disp, button: &str, count: i64) -> Result<()> {
    for _ in 0..count.max(0) {
        let pressed = sway_cmd(ctx, disp, &format!("seat seat0 cursor press {button}"));
        let released = sway_cmd(ctx, disp, &format!("seat seat0 cursor release {button}"));
        released?;
        pressed?;
    }
    Ok(())
}

pub fn cmd_click(ctx: &Ctx, btn: &str, at: Option<(i64, i64)>, count: i64) -> Result<i32> {
    let disp = display(ctx)?;
    if let Some((x, y)) = at {
        check_point(ctx, &disp, x, y)?;
        sway_cmd(ctx, &disp, &format!("seat seat0 cursor set {x} {y}"))?;
    }
    press(ctx, &disp, button(btn), count)?;
    Ok(0)
}

pub fn cmd_scroll(ctx: &Ctx, direction: &str, steps: i64) -> Result<i32> {
    let disp = display(ctx)?;
    press(ctx, &disp, scroll_button(direction), steps)?;
    Ok(0)
}

pub fn cmd_hold_input(ctx: &Ctx) -> Result<i32> {
    let rt = PathBuf::from(ctx.env.get("XDG_RUNTIME_DIR").unwrap_or(""));
    if rt.file_name().is_none_or(|n| n != "agent-display") {
        bail!("hold-input only runs inside the agent display");
    }
    let (Some(wl), Some(sock)) = (ctx.env.get("WAYLAND_DISPLAY"), ctx.env.get("SWAYSOCK")) else {
        bail!("hold-input only runs inside the agent display");
    };
    crate::hold_input::hold_input(ctx, &rt.join(wl), Path::new(sock))?;
    Ok(0)
}

