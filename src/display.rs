pub fn cmd_start(ctx: &Ctx, size: &str, renderer: Option<&str>) -> Result<i32> {
    require(ctx, &["sway", "swaymsg", "dbus-run-session", "systemd-run"])?;
    if ctx.sys.unit_active(ctx, DISPLAY_UNIT) {
        let disp = display(ctx)?;
        ctx.println(&format!("agent display already running: {}", status_line(ctx, &disp)?));
        return Ok(0);
    }
    let rt = ensure_runtime_dir(ctx)?;
    for name in ["env", "env.tmp"] {
        unlink_missing_ok(&rt.join(name));
    }
    let exe = crate::util::resolve(&ctx.exe);
    write_private(&rt.join("sway.config"), &sway_config(OUTPUT, size, &exe))?;
    write_private(&rt.join("dbus.conf"), &dbus_config(&rt))?;
    let mut env = Environ::default();
    for k in PASS_ENV {
        if let Some(v) = ctx.env.get(k) {
            env.set(k, v);
        }
    }
    env.set("XDG_RUNTIME_DIR", rt.to_string_lossy());
    env.set("WLR_BACKENDS", "headless");
    env.set("WLR_LIBINPUT_NO_DEVICES", "1");
    env.set("WLR_HEADLESS_OUTPUTS", "1");
    if let Some(r) = renderer {
        env.set("WLR_RENDERER", r);
    }
    let mut argv = env_argv(&env);
    argv.push(which("dbus-run-session", &ctx.env).unwrap().to_string_lossy().into());
    argv.push(format!("--config-file={}", rt.join("dbus.conf").display()));
    argv.push("--".into());
    argv.push(which("sway", &ctx.env).unwrap().to_string_lossy().into());
    argv.push("--config".into());
    argv.push(rt.join("sway.config").to_string_lossy().into());
    ctx.sys.systemd_run(ctx, DISPLAY_UNIT.trim_end_matches(".service"), &argv, false, None, Some("Agent headless display (sway)"))?;
    let deadline = Instant::now() + Duration::from_secs(15);
    let disp = loop {
        match display(ctx) {
            Ok(d) => break d,
            Err(e) => {
                if Instant::now() > deadline || !ctx.sys.unit_active(ctx, DISPLAY_UNIT) {
                    bail!("{e}\n{}", journal_tail(ctx, DISPLAY_UNIT, 12));
                }
                ctx.sys.sleep(0.2);
            }
        }
    };
    ctx.println(&format!("agent display started: {}", status_line(ctx, &disp)?));
    Ok(0)
}

pub fn cmd_stop(ctx: &Ctx) -> Result<i32> {
    let units = agent_units(ctx, "agent-display");
    // Browsers first, cleanly (cookie flush); then other dependents; then
    // the display. BindsTo would stop them too, but SIGTERM loses cookies.
    let browsers: Vec<String> = units
        .iter()
        .filter(|u| u.starts_with(BROWSER_UNIT))
        .map(|u| u.trim_end_matches(".service").to_string())
        .collect();
    browser::close_browsers(ctx, &browsers)?;
    let rest = agent_units(ctx, "agent-display");
    let deps: Vec<String> = rest.iter().filter(|u| *u != DISPLAY_UNIT).cloned().collect();
    ctx.sys.stop_units(ctx, &deps)?;
    let disp: Vec<String> = rest.iter().filter(|u| *u == DISPLAY_UNIT).cloned().collect();
    ctx.sys.stop_units(ctx, &disp)?;
    let rt = ctx.runtime_dir();
    for name in ["env", "env.tmp", "vnc.port"] {
        unlink_missing_ok(&rt.join(name));
    }
    let _ = std::fs::remove_dir_all(ctx.tab_outputs_dir());
    let _ = std::fs::remove_dir_all(ctx.vnc_dir());
    if let Ok(rd) = std::fs::read_dir(ctx.browsers_dir()) {
        for e in rd.flatten() {
            if e.path().extension().is_some_and(|x| x == "json" || x == "owner") {
                unlink_missing_ok(&e.path());
            }
        }
    }
    ctx.println(&format!("stopped: {}", if units.is_empty() { "nothing was running".into() } else { units.join(", ") }));
    Ok(0)
}

pub fn cmd_status(ctx: &Ctx) -> Result<i32> {
    let units = agent_units(ctx, "agent-display");
    ctx.println(&format!("units: {}", if units.is_empty() { "none".into() } else { units.join(", ") }));
    let disp = match display(ctx) {
        Ok(d) => d,
        Err(e) => {
            ctx.println(&format!("display: {e}"));
            return Ok(1);
        }
    };
    ctx.println(&format!("display: {}", status_line(ctx, &disp)?));
    for b in ctx.sys.browsers(ctx) {
        let port = b.0.get("port").map(|p| json::dumps(p, true)).unwrap_or_else(|| "None".into());
        let port = if port == "null" { "None".into() } else { port };
        ctx.println(&format!(
            "browser: {} cdp=http://127.0.0.1:{port} profile={}{}",
            b.unit(),
            b.profile(),
            if b.temp() { " (temp)" } else { "" }
        ));
    }
    if ctx.sys.unit_active(ctx, VNC_UNIT) {
        ctx.println(&format!("viewer: {VNC_UNIT} (see `agent-display view`)"));
    }
    ctx.println(&format!("windows: {}", windows(ctx, &disp)?.len()));
    Ok(0)
}

/// Shell exports for the agent display. XDG_RUNTIME_DIR stays the user's
/// (exporting the agent one would break `systemctl --user` and this tool
/// in that shell), so WAYLAND_DISPLAY is an absolute path.
pub fn env_exports(disp: &Disp) -> String {
    let mut lines = vec![format!("unset {}", BLOCKED_ENV.join(" "))];
    for (k, v) in disp.env().0 {
        if k == "XDG_RUNTIME_DIR" {
            continue;
        }
        let v = if k == "WAYLAND_DISPLAY" { Path::new(&disp.runtime).join(&v).to_string_lossy().into_owned() } else { v };
        lines.push(format!("export {k}={}", shquote(&v)));
    }
    lines.join("\n")
}

pub fn cmd_env(ctx: &Ctx) -> Result<i32> {
    ctx.println(&env_exports(&display(ctx)?));
    Ok(0)
}

fn strip_dashdash(argv: &[String]) -> &[String] {
    if argv.first().is_some_and(|a| a == "--") { &argv[1..] } else { argv }
}

pub fn cmd_exec(ctx: &Ctx, argv: &[String]) -> Result<i32> {
    let disp = display(ctx)?;
    let argv = strip_dashdash(argv);
    if argv.is_empty() {
        bail!("usage: agent-display exec -- COMMAND [ARG...]");
    }
    let mut env = ctx.clean_env();
    env.extend(&disp.env());
    let mut cmd = std::process::Command::new(&argv[0]);
    cmd.args(&argv[1..]).env_clear();
    for (k, v) in &env.0 {
        cmd.env(k, v);
    }
    let _ = ctx.out.borrow_mut().flush();
    let st = cmd.status().map_err(|e| Error::new(crate::util::python_spawn_error(&e, &argv[0])))?;
    Ok(crate::util::exit_code(st))
}

pub fn cmd_launch(ctx: &Ctx, name: &str, argv: &[String]) -> Result<i32> {
    let disp = display(ctx)?;
    let valid = {
        let b = name.as_bytes();
        !b.is_empty()
            && b.len() <= 41
            && (b[0].is_ascii_lowercase() || b[0].is_ascii_digit())
            && b.iter().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == b'-')
    };
    if !valid {
        bail!("name: lowercase letters, digits and hyphens");
    }
    let argv = strip_dashdash(argv);
    if argv.is_empty() {
        bail!("usage: agent-display launch NAME -- COMMAND [ARG...]");
    }
    let Some(exe) = which(&argv[0], &ctx.env) else {
        bail!("{}: not found", argv[0]);
    };
    let unit = format!("{APP_PREFIX}{name}");
    if ctx.sys.unit_active(ctx, &unit) {
        bail!("{unit} is already running");
    }
    let mut full = env_argv(&ctx.minimal_env(&disp));
    full.push(exe.to_string_lossy().into());
    full.extend(argv[1..].iter().cloned());
    ctx.sys.systemd_run(ctx, &unit, &full, true, None, None)?;
    ctx.println(&format!("launched {unit}; stop with: systemctl --user stop {unit}"));
    Ok(0)
}

