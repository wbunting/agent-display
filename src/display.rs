pub fn cmd_focus(ctx: &Ctx, id: i64) -> Result<i32> {
    let disp = display(ctx)?;
    if !windows(ctx, &disp)?.iter().any(|w| w.id == id) {
        bail!("no window with id {id} on the agent display");
    }
    sway_cmd(ctx, &disp, &format!("[con_id={id}] focus"))?;
    Ok(0)
}

pub fn cmd_screenshot(ctx: &Ctx, path: &str, window: Option<i64>) -> Result<i32> {
    require(ctx, &["grim"])?;
    let disp = display(ctx)?;
    let mut argv = vec!["grim".to_string()];
    if let Some(id) = window {
        let wins = windows(ctx, &disp)?;
        let Some(win) = wins.iter().find(|w| w.id == id) else {
            bail!("no window with id {id}");
        };
        let r = &win.rect;
        let n = |k: &str| json::dumps(&r[k], true);
        argv.extend(["-g".into(), format!("{},{} {}x{}", n("x"), n("y"), n("width"), n("height"))]);
    } else {
        argv.extend(["-o".into(), OUTPUT.into()]);
    }
    let abs = absolute(Path::new(path));
    argv.push(abs.to_string_lossy().into());
    let mut env = ctx.clean_env();
    env.extend(&disp.env());
    {
        let _mask = crate::util::Umask::set(0o077);
        ctx.sys.run(ctx, &argv, Some(&env), Some(30.0), true)?;
    }
    ctx.println(&abs.to_string_lossy());
    Ok(0)
}

